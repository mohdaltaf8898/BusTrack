#!/usr/bin/env python3
"""Regenerate the insert-only Supabase seed from the bundled 2025–26 catalogue.

Run with Python 3 from any directory: python3 scripts/generate_seed.py
The catalogue, not this script, is the source of names, times and locations.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROUTES = json.loads((ROOT / "data/lords-routes-2025-26.json").read_text(encoding="utf-8"))
COLORS = ["#2563eb", "#0f766e", "#7c3aed", "#d97706", "#db2777", "#0891b2"]
DESCRIPTION = "Morning pickup order from the 2025–26 college route document. Confirm current service with the transport office."


def sql(value):
    if value is None:
        return "null"
    if isinstance(value, (dict, list)):
        return sql(json.dumps(value, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def duration(first, last):
    if not first or not last:
        return None
    a, b = (int(first[:2]) * 60 + int(first[3:])), (int(last[:2]) * 60 + int(last[3:]))
    return b - a if b > a else None


out = ["""-- GENERATED by scripts/generate_seed.py from data/lords-routes-2025-26.json.
-- Historical 2025–26 timetable; current service is NOT independently verified.
-- Coordinates are approximations, not official pickup positions or GPS traces.
-- Contains data provided by TGSRTC. No driver names, phone numbers or credentials.
-- Apply all three migrations first. Reruns do not overwrite existing operator data.
-- The SIM-* vehicles are placeholders and must be replaced for real operations.
-- Do not mark a route verified until transport staff supply a validated corridor.

begin;
"""]
for index, route in enumerate(ROUTES):
    number = f"{route['number']:02d}"
    route_id = f"route-{number}"
    first, last = route["stops"][0], route["stops"][-1]
    span = duration(first["scheduledTime"], last["scheduledTime"])
    shape, indices = [], []
    for stop in route["stops"]:
        location = stop["location"]
        if location is None:
            indices.append(-1)
            continue
        point = {"lat": location["lat"], "lng": location["lng"]}
        if not shape or shape[-1] != point:
            shape.append(point)
        indices.append(len(shape) - 1)
    if len(shape) < 2:
        raise ValueError(f"{route_id} needs at least two mapped stops")
    fields = [
        route_id, f"Route {number}", f"{first['name']} → Lords College", first["name"], "Lords College",
        f"SIM-{number}", DESCRIPTION, 25, span if span is not None else 45, "scheduled",
        COLORS[index % len(COLORS)], shape, indices, "straight", "2025–26", span,
    ]
    out.append("""insert into public.routes (
  id, code, route_name, start_location, destination, bus_number, description,
  average_speed_kmh, estimated_duration_minutes, status, color, shape, stop_indices,
  geometry_source, schedule_year, scheduled_duration_minutes
) values (\n  """ + ", ".join(sql(value) for value in fields) + "\n) on conflict do nothing;\n")
    out.append("insert into public.stops (id, route_id, stop_name, latitude, longitude, stop_order, scheduled_time, location_source, location_reference, note) values\n")
    rows = []
    for stop_index, stop in enumerate(route["stops"], start=1):
        location = stop["location"] or {}
        row = [f"r{number}-s{stop_index:02d}", route_id, stop["name"], location.get("lat"), location.get("lng"),
               stop_index, stop["scheduledTime"], location.get("source"), location.get("reference"), stop.get("note")]
        rows.append("  (" + ", ".join(sql(value) for value in row) + ")")
    out.append(",\n".join(rows) + "\non conflict do nothing;\n")
    bus = [f"bus-sim{number}", f"SIM-{number}", route_id, None, "scheduled", "Simulation vehicle", "2025–26 pickup times; current service not verified"]
    out.append("insert into public.buses (id, bus_number, assigned_route_id, capacity, status, model, service_availability) values\n  (" + ", ".join(sql(value) for value in bus) + ") on conflict do nothing;\n")
out.append("commit;\n")
(ROOT / "supabase/seed.sql").write_text("\n".join(out), encoding="utf-8")
print(f"Wrote {len(ROUTES)} historical routes to supabase/seed.sql")
